n_divisor = int(input("Введіть число N, на яке має ділитися число Фібоначчі: "))

a, b = 1, 1
print("Послідовність:", end=" ")

while True:
    print(a, end=" ")
    
    # Перевірка умови зупинки
    if a % n_divisor == 0:
        print(f"Зупинка: число {a} ділиться на {n_divisor} націло.")
        break
    
    # Обчислення наступного числа Фібоначчі
    a, b = b, a + b